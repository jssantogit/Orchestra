export const DIRECT_WORK_STATES = Object.freeze({
  INTAKE: 'INTAKE',
  RESOLVING: 'RESOLVING',
  IMPLEMENTATION_READY: 'IMPLEMENTATION_READY',
  IMPLEMENTING: 'IMPLEMENTING',
  CANDIDATE_READY: 'CANDIDATE_READY',
  EVIDENCE_PENDING: 'EVIDENCE_PENDING',
  AUDIT_PENDING: 'AUDIT_PENDING',
  ACCEPTANCE: 'ACCEPTANCE',
  DONE: 'DONE',
  BLOCKED: 'BLOCKED',
  HUMAN_GATE: 'HUMAN_GATE',
});

const TRANSITIONS = Object.freeze({
  [DIRECT_WORK_STATES.INTAKE]: Object.freeze({ RESOLVE: DIRECT_WORK_STATES.RESOLVING }),
  [DIRECT_WORK_STATES.RESOLVING]: Object.freeze({
    PACKET_READY: DIRECT_WORK_STATES.IMPLEMENTATION_READY,
    BLOCK: DIRECT_WORK_STATES.BLOCKED,
    REQUIRE_HUMAN: DIRECT_WORK_STATES.HUMAN_GATE,
  }),
  [DIRECT_WORK_STATES.IMPLEMENTATION_READY]: Object.freeze({ IMPLEMENT: DIRECT_WORK_STATES.IMPLEMENTING }),
  [DIRECT_WORK_STATES.IMPLEMENTING]: Object.freeze({
    CANDIDATE_CREATED: DIRECT_WORK_STATES.CANDIDATE_READY,
    BLOCK: DIRECT_WORK_STATES.BLOCKED,
    REQUIRE_HUMAN: DIRECT_WORK_STATES.HUMAN_GATE,
  }),
  [DIRECT_WORK_STATES.CANDIDATE_READY]: Object.freeze({
    VERIFY: DIRECT_WORK_STATES.EVIDENCE_PENDING,
    ACCEPT_WITHOUT_AUDIT: DIRECT_WORK_STATES.ACCEPTANCE,
  }),
  [DIRECT_WORK_STATES.EVIDENCE_PENDING]: Object.freeze({
    EVIDENCE_READY_AUDIT_PENDING: DIRECT_WORK_STATES.AUDIT_PENDING,
    VERIFICATION_READY: DIRECT_WORK_STATES.ACCEPTANCE,
    BLOCK: DIRECT_WORK_STATES.BLOCKED,
  }),
  [DIRECT_WORK_STATES.AUDIT_PENDING]: Object.freeze({
    VERIFICATION_READY: DIRECT_WORK_STATES.ACCEPTANCE,
    BLOCK: DIRECT_WORK_STATES.BLOCKED,
  }),
  [DIRECT_WORK_STATES.ACCEPTANCE]: Object.freeze({
    ACCEPT: DIRECT_WORK_STATES.DONE,
    BLOCK: DIRECT_WORK_STATES.BLOCKED,
    REQUIRE_HUMAN: DIRECT_WORK_STATES.HUMAN_GATE,
  }),
  [DIRECT_WORK_STATES.HUMAN_GATE]: Object.freeze({ RESUME: DIRECT_WORK_STATES.RESOLVING }),
});

export function transitionDirectWork(state, event) {
  if (!Object.values(DIRECT_WORK_STATES).includes(state)) {
    return Object.freeze({ allowed: false, nextState: state, reason: 'STATE_INVALID' });
  }
  const nextState = TRANSITIONS[state]?.[event];
  if (!nextState) {
    return Object.freeze({ allowed: false, nextState: state, reason: 'TRANSITION_NOT_ALLOWED' });
  }
  return Object.freeze({ allowed: true, nextState, reason: 'TRANSITION_ALLOWED' });
}
